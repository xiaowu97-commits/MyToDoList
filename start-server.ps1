# Lightweight Local HTTP Server for MyToDoList
# Pure ASCII for maximum Windows PowerShell 5.1 compatibility

$port = 8080
$prefix = "http://localhost:$port/"
$rootDir = $PSScriptRoot

$listener = New-Object System.Net.HttpListener
$listener.Prefixes.Add($prefix)

try {
    $listener.Start()
} catch {
    Write-Host "Port 8080 busy, trying 8081..."
    $port = 8081
    $prefix = "http://localhost:$port/"
    $listener = New-Object System.Net.HttpListener
    $listener.Prefixes.Add($prefix)
    $listener.Start()
}

Write-Host "MyToDoList Server listening on: $prefix"
Write-Host "Root folder: $rootDir"

$mimeTypes = @{
    ".html" = "text/html; charset=utf-8";
    ".js"   = "application/javascript; charset=utf-8";
    ".css"  = "text/css; charset=utf-8";
    ".json" = "application/json; charset=utf-8";
    ".png"  = "image/png";
    ".jpg"  = "image/jpeg";
    ".svg"  = "image/svg+xml";
    ".ico"  = "image/x-icon"
}

try {
    while ($listener.IsListening) {
        $context = $listener.GetContext()
        $request = $context.Request
        $response = $context.Response

        $cleanPath = $request.Url.LocalPath.TrimStart('/')
        if ([string]::IsNullOrEmpty($cleanPath) -or $cleanPath -eq "/") {
            $cleanPath = "index.html"
        }

        $targetPath = Join-Path $rootDir $cleanPath

        if (Test-Path $targetPath -PathType Leaf) {
            $ext = [System.IO.Path]::GetExtension($targetPath).ToLower()
            $contentType = "application/octet-stream"
            if ($mimeTypes.ContainsKey($ext)) {
                $contentType = $mimeTypes[$ext]
            }
            $response.ContentType = $contentType
            $bytes = [System.IO.File]::ReadAllBytes($targetPath)
            $response.ContentLength64 = $bytes.Length
            $response.OutputStream.Write($bytes, 0, $bytes.Length)
        } else {
            $response.StatusCode = 404
            $errBytes = [System.Text.Encoding]::UTF8.GetBytes("File Not Found")
            $response.ContentLength64 = $errBytes.Length
            $response.OutputStream.Write($errBytes, 0, $errBytes.Length)
        }
        $response.Close()
    }
} finally {
    $listener.Stop()
}
